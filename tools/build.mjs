// tool: node >= 18 | 生成 assets/payload.js —— 明文字符串在构建期被编码成点阵并加密，仓库里只留密文
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

const ITER = 210000;          // PBKDF2 迭代，与 assets/app.js 的 IT 保持一致
const MAGIC = 0x51;           // 明文头部魔数
const ORDER = [2, 0, 3, 1];   // 密钥分片落盘顺序，与 app.js 的 P.o 对应

// 分片掩码，必须与 assets/app.js 的 MASK 完全一致
const MASK = [
  [0x5a, 0x11, 0x9c, 0x42, 0xe7, 0x08, 0x6d, 0xb3],
  [0x2f, 0x84, 0x3d, 0xc6, 0x51, 0x9a, 0x07, 0xe2],
  [0x71, 0xca, 0x05, 0x38, 0x9f, 0x24, 0xdc, 0x6a],
  [0xbe, 0x37, 0x60, 0xd5, 0x0a, 0x7c, 0x93, 0x1e],
];

const CH_FILE = fs.existsSync(path.join(HERE, 'channels.local.json'))
  ? path.join(HERE, 'channels.local.json')
  : path.join(HERE, 'channels.example.json');

const SECRET_FILE = path.join(HERE, 'secret.local.json');

function loadSecret() {
  if (fs.existsSync(SECRET_FILE)) {
    const raw = JSON.parse(fs.readFileSync(SECRET_FILE, 'utf8'));
    if (!/^[0-9a-f]{64}$/.test(raw.secret)) throw new Error('secret.local.json 格式不对');
    return Buffer.from(raw.secret, 'hex');
  }
  const s = crypto.randomBytes(32);
  fs.writeFileSync(SECRET_FILE, JSON.stringify({ secret: s.toString('hex') }, null, 2) + '\n');
  console.log('生成新主密钥 tools/secret.local.json —— 别提交、别丢，丢了所有密文都要重建');
  return s;
}

// 二维码点阵 -> [MAGIC][size][bitmap bytes]
function packModules(mod) {
  const size = mod.size;
  const bits = size * size;
  const buf = Buffer.alloc(2 + Math.ceil(bits / 8));
  buf[0] = MAGIC;
  buf[1] = size;
  for (let i = 0; i < bits; i++) {
    if (mod.data[i]) buf[2 + (i >> 3)] |= 0x80 >> (i & 7);
  }
  return buf;
}

// 布局: salt(16) | iv(12) | ciphertext | tag(16)，整体 base64
function seal(plain, aad, secret) {
  const salt = crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const key = crypto.pbkdf2Sync(secret, salt, ITER, 32, 'sha256');
  const c = crypto.createCipheriv('aes-256-gcm', key, iv);
  c.setAAD(Buffer.from(aad, 'utf8'));
  const ct = Buffer.concat([c.update(plain), c.final()]);
  return Buffer.concat([salt, iv, ct, c.getAuthTag()]).toString('base64');
}

function splitSecret(secret) {
  const out = [];
  for (const idx of ORDER) {
    const b = Buffer.alloc(8);
    for (let k = 0; k < 8; k++) b[k] = secret[idx * 8 + k] ^ MASK[idx][k];
    out.push(b.toString('base64'));
  }
  return out;
}

const channels = JSON.parse(fs.readFileSync(CH_FILE, 'utf8'));
if (!Array.isArray(channels) || !channels.length) throw new Error('渠道列表为空');

const seen = new Set();
const items = channels.map((ch, i) => {
  const id = String(ch.id || `c${i + 1}`).trim();
  const name = String(ch.name || '').trim();
  const url = String(ch.url || '').trim();
  if (!name) throw new Error(`第 ${i + 1} 条缺少 name`);
  if (!url) throw new Error(`渠道 ${name} 缺少 url`);
  if (seen.has(id)) throw new Error(`id 重复: ${id}`);
  seen.add(id);

  const qr = QRCode.create(url, { errorCorrectionLevel: 'M' });
  const plain = packModules(qr.modules);
  const d = seal(plain, id, loadSecret());
  console.log(`  ${name.padEnd(12, ' ')} id=${id.padEnd(12)} 点阵=${qr.modules.size}x${qr.modules.size} 密文=${d.length}B`);
  return { i: id, n: name, d };
});

const payload =
  '/* generated by tools/build.mjs — 请勿手改 */\n' +
  `self.__Q=${JSON.stringify({ s: splitSecret(loadSecret()), o: ORDER, c: items })};\n`;

fs.writeFileSync(path.join(ROOT, 'assets', 'payload.js'), payload);

console.log('');
console.log(`输出 assets/payload.js  (${Buffer.byteLength(payload)} B, ${items.length} 个渠道)`);
console.log('源文件 ' + path.relative(ROOT, CH_FILE) + ' —— 明文，不要提交');
